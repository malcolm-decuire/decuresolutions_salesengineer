import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

const [contractArgument, seedArgument, outputArgument] = process.argv.slice(2);

if (!contractArgument || !seedArgument || !outputArgument) {
  console.error(
    "Usage: node scripts/compile-workbook-seed.mjs <contract.json> <seed.ndjson> <output.ts>",
  );
  process.exit(1);
}

const contractPath = resolve(contractArgument);
const seedPath = resolve(seedArgument);
const outputPath = resolve(outputArgument);
const contract = JSON.parse(readFileSync(contractPath, "utf8"));
const records = readFileSync(seedPath, "utf8")
  .trim()
  .split("\n")
  .filter(Boolean)
  .map((line) => JSON.parse(line));

const sheetIndex = new Map(
  contract.sheets.map((sheet, index) => [sheet.name, index]),
);

const parseAddress = (address) => {
  const match = /^([A-Z]+)(\d+)$/.exec(address);
  if (!match) throw new Error(`Unsupported cell address: ${address}`);
  const column = [...match[1]].reduce(
    (total, character) => total * 26 + character.charCodeAt(0) - 64,
    0,
  );
  return { row: Number(match[2]), column };
};

const kind = (type) => {
  if (type === "number") return "n";
  if (type === "string") return "s";
  if (type === "boolean") return "b";
  if (type === "error") return "e";
  throw new Error(`Unsupported seed value type: ${type}`);
};

const tuples = records.map((record) => {
  const sheet = sheetIndex.get(record.sheet);
  if (sheet === undefined)
    throw new Error(`Seed references unknown sheet: ${record.sheet}`);
  const address = parseAddress(record.address);
  return [
    sheet,
    address.row,
    address.column,
    kind(record.value.type),
    record.value.value,
  ];
});

const validations = contract.sheets.flatMap((sheet, index) =>
  sheet.validations.map((validation) => ({ sheet: index, ...validation })),
);

const moduleSource = `// Generated by scripts/compile-workbook-seed.mjs. Do not edit by hand.
export const WORKBOOK_SOURCE_SHA256 = ${JSON.stringify(contract.source.sha256)} as const
export const WORKBOOK_SEED_SHA256 = ${JSON.stringify(contract.workbook.seedOracle.sha256)} as const
export const WORKBOOK_SEED_RECORD_COUNT = ${tuples.length} as const

export type EncodedSeedRecord = readonly [
  sheetIndex: number,
  row: number,
  column: number,
  kind: 'n' | 's' | 'b' | 'e',
  value: number | string | boolean,
]

export const ENCODED_WORKBOOK_SEED: readonly EncodedSeedRecord[] = ${JSON.stringify(tuples)}

export const WORKBOOK_VALIDATIONS = ${JSON.stringify(validations, null, 2)} as const
`;

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, moduleSource);
console.log(
  JSON.stringify({
    outputPath,
    records: tuples.length,
    validations: validations.length,
  }),
);
