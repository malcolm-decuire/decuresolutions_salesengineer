import { createHash } from 'node:crypto'
import { execFileSync } from 'node:child_process'
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'

const [workbookArgument, outputArgument] = process.argv.slice(2)
if (!workbookArgument || !outputArgument) {
  console.error('Usage: node scripts/compile-workbook-charts.mjs <workbook.xlsx> <output.ts>')
  process.exit(1)
}

const workbook = resolve(workbookArgument)
const output = resolve(outputArgument)
const entries = execFileSync('unzip', ['-Z1', workbook], { encoding: 'utf8' }).trim().split('\n')
  .filter((entry) => /^xl\/charts\/chart\d+\.xml$/.test(entry))
  .sort((left, right) => Number(left.match(/\d+/)[0]) - Number(right.match(/\d+/)[0]))

const charts = entries.map((entry, index) => {
  const xml = execFileSync('unzip', ['-p', workbook, entry], { encoding: 'utf8', maxBuffer: 16 * 1024 * 1024 })
  const title = /<c:title>.*?<a:t>(.*?)<\/a:t>/s.exec(xml)?.[1]
  const barDirection = /<c:barDir val="([^"]+)"/.exec(xml)?.[1]
  const grouping = /<c:grouping val="([^"]+)"/.exec(xml)?.[1]
  const series = [...xml.matchAll(/<c:ser>(.*?)<\/c:ser>/gs)].map((match) => {
    const body = match[1]
    const name = /<c:tx>.*?<c:v>(.*?)<\/c:v>/s.exec(body)?.[1]
    const formulas = [...body.matchAll(/<c:f>(.*?)<\/c:f>/gs)].map((formula) => formula[1].replaceAll('&apos;', "'"))
    if (!name || formulas.length !== 2) throw new Error(`${entry} contains an unsupported series contract`)
    return { name, categories: parseRange(formulas[0]), values: parseRange(formulas[1]) }
  })
  if (!title || barDirection !== 'col' || grouping !== 'stacked' || series.length !== 3) {
    throw new Error(`${entry} no longer matches the required stacked-column chart contract`)
  }
  const category = JSON.stringify(series[0].categories)
  if (!series.every((item) => JSON.stringify(item.categories) === category)) throw new Error(`${entry} series categories are inconsistent`)
  return {
    id: `chart-${index + 1}`,
    part: entry,
    partSha256: createHash('sha256').update(xml).digest('hex'),
    title,
    type: 'stacked-column',
    categories: series[0].categories,
    series: series.map(({ name, values }) => ({ name, values })),
  }
})

if (charts.length !== 4) throw new Error(`Expected four workbook charts, found ${charts.length}`)
const source = `// Generated by scripts/compile-workbook-charts.mjs. Do not edit by hand.\nexport const WORKBOOK_CHARTS = ${JSON.stringify(charts, null, 2)} as const\n`
mkdirSync(dirname(output), { recursive: true })
writeFileSync(output, source)
console.log(JSON.stringify({ output, charts: charts.length, series: charts.reduce((total, chart) => total + chart.series.length, 0) }))

function parseRange(formula) {
  const match = /^(?:'((?:[^']|'')+)'|([^!]+))!\$([A-Z]+)\$(\d+):\$([A-Z]+)\$(\d+)$/.exec(formula)
  if (!match) throw new Error(`Unsupported chart range ${formula}`)
  return {
    sheet: (match[1] ?? match[2]).replaceAll("''", "'"),
    startRow: Number(match[4]),
    endRow: Number(match[6]),
    startColumn: columnNumber(match[3]),
    endColumn: columnNumber(match[5]),
    formula,
  }
}

function columnNumber(letters) {
  return [...letters].reduce((total, character) => total * 26 + character.charCodeAt(0) - 64, 0)
}
